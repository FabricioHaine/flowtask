-- ==========================================================================
-- FlowTask - Esquema inicial (compatível com PostgreSQL e H2 p/ testes)
-- Tabelas, chaves estrangeiras, restrições e índices essenciais.
-- ==========================================================================

CREATE TABLE usuarios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(120)  NOT NULL,
    email         VARCHAR(255)  NOT NULL,
    senha_hash    VARCHAR(120)  NOT NULL,
    criado_em     TIMESTAMP     NOT NULL,
    atualizado_em TIMESTAMP     NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);

CREATE TABLE projetos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(140)  NOT NULL,
    descricao     VARCHAR(1000),
    estado        VARCHAR(20)   NOT NULL,
    data_inicio   DATE,
    prazo_final   DATE,
    dono_id       BIGINT        NOT NULL,
    criado_em     TIMESTAMP     NOT NULL,
    atualizado_em TIMESTAMP     NOT NULL,
    versao        BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT fk_projetos_dono FOREIGN KEY (dono_id) REFERENCES usuarios (id),
    CONSTRAINT ck_projetos_estado CHECK (estado IN ('PLANEJADO', 'ATIVO', 'PAUSADO', 'CONCLUIDO', 'ARQUIVADO'))
);

-- Associação usuário ↔ projeto com a função do usuário naquele projeto.
CREATE TABLE membros_projeto (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projeto_id BIGINT       NOT NULL,
    usuario_id BIGINT       NOT NULL,
    funcao     VARCHAR(20)  NOT NULL,
    criado_em  TIMESTAMP    NOT NULL,
    CONSTRAINT fk_membros_projeto FOREIGN KEY (projeto_id) REFERENCES projetos (id),
    CONSTRAINT fk_membros_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT uk_membros_projeto_usuario UNIQUE (projeto_id, usuario_id),
    CONSTRAINT ck_membros_funcao CHECK (funcao IN ('OWNER', 'MANAGER', 'MEMBER'))
);

CREATE TABLE convites_projeto (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projeto_id      BIGINT       NOT NULL,
    email           VARCHAR(255) NOT NULL,
    funcao_proposta VARCHAR(20)  NOT NULL,
    criado_por      BIGINT       NOT NULL,
    criado_em       TIMESTAMP    NOT NULL,
    expira_em       TIMESTAMP    NOT NULL,
    estado          VARCHAR(20)  NOT NULL,
    CONSTRAINT fk_convites_projeto FOREIGN KEY (projeto_id) REFERENCES projetos (id),
    CONSTRAINT fk_convites_criador FOREIGN KEY (criado_por) REFERENCES usuarios (id),
    CONSTRAINT ck_convites_estado CHECK (estado IN ('PENDENTE', 'ACEITO', 'RECUSADO', 'EXPIRADO', 'CANCELADO')),
    CONSTRAINT ck_convites_funcao CHECK (funcao_proposta IN ('OWNER', 'MANAGER', 'MEMBER'))
);
CREATE INDEX idx_convites_email_estado ON convites_projeto (email, estado);

CREATE TABLE colunas_kanban (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projeto_id        BIGINT      NOT NULL,
    nome              VARCHAR(80) NOT NULL,
    ordem             INT         NOT NULL,
    ativa             BOOLEAN     NOT NULL DEFAULT TRUE,
    coluna_conclusao  BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_colunas_projeto FOREIGN KEY (projeto_id) REFERENCES projetos (id) ON DELETE CASCADE
);
CREATE INDEX idx_colunas_projeto ON colunas_kanban (projeto_id, ordem);

CREATE TABLE tarefas (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projeto_id      BIGINT        NOT NULL,
    coluna_id       BIGINT        NOT NULL,
    titulo          VARCHAR(160)  NOT NULL,
    descricao       VARCHAR(4000),
    prioridade      VARCHAR(20)   NOT NULL,
    criador_id      BIGINT        NOT NULL,
    responsavel_id  BIGINT,
    prazo           DATE,
    data_conclusao  TIMESTAMP,
    ordem           INT           NOT NULL,
    arquivada       BOOLEAN       NOT NULL DEFAULT FALSE,
    criado_em       TIMESTAMP     NOT NULL,
    atualizado_em   TIMESTAMP     NOT NULL,
    versao          BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT fk_tarefas_projeto FOREIGN KEY (projeto_id) REFERENCES projetos (id) ON DELETE CASCADE,
    CONSTRAINT fk_tarefas_coluna FOREIGN KEY (coluna_id) REFERENCES colunas_kanban (id),
    CONSTRAINT fk_tarefas_criador FOREIGN KEY (criador_id) REFERENCES usuarios (id),
    CONSTRAINT fk_tarefas_responsavel FOREIGN KEY (responsavel_id) REFERENCES usuarios (id),
    CONSTRAINT ck_tarefas_prioridade CHECK (prioridade IN ('BAIXA', 'MEDIA', 'ALTA', 'CRITICA'))
);
CREATE INDEX idx_tarefas_projeto ON tarefas (projeto_id, arquivada);
CREATE INDEX idx_tarefas_coluna ON tarefas (coluna_id, ordem);
CREATE INDEX idx_tarefas_responsavel ON tarefas (responsavel_id);
CREATE INDEX idx_tarefas_prazo ON tarefas (prazo);

CREATE TABLE etiquetas (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projeto_id BIGINT      NOT NULL,
    nome       VARCHAR(40) NOT NULL,
    cor        VARCHAR(9),
    CONSTRAINT fk_etiquetas_projeto FOREIGN KEY (projeto_id) REFERENCES projetos (id) ON DELETE CASCADE,
    CONSTRAINT uk_etiquetas_projeto_nome UNIQUE (projeto_id, nome)
);

CREATE TABLE tarefas_etiquetas (
    tarefa_id  BIGINT NOT NULL,
    etiqueta_id BIGINT NOT NULL,
    PRIMARY KEY (tarefa_id, etiqueta_id),
    CONSTRAINT fk_tarefas_etiquetas_tarefa FOREIGN KEY (tarefa_id) REFERENCES tarefas (id) ON DELETE CASCADE,
    CONSTRAINT fk_tarefas_etiquetas_etiqueta FOREIGN KEY (etiqueta_id) REFERENCES etiquetas (id) ON DELETE CASCADE
);

CREATE TABLE comentarios (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarefa_id  BIGINT        NOT NULL,
    autor_id   BIGINT        NOT NULL,
    conteudo   VARCHAR(4000) NOT NULL,
    criado_em  TIMESTAMP     NOT NULL,
    editado_em TIMESTAMP,
    CONSTRAINT fk_comentarios_tarefa FOREIGN KEY (tarefa_id) REFERENCES tarefas (id) ON DELETE CASCADE,
    CONSTRAINT fk_comentarios_autor FOREIGN KEY (autor_id) REFERENCES usuarios (id)
);
CREATE INDEX idx_comentarios_tarefa ON comentarios (tarefa_id, criado_em);

CREATE TABLE atividades (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projeto_id        BIGINT       NOT NULL,
    usuario_id        BIGINT       NOT NULL,
    tipo              VARCHAR(60)  NOT NULL,
    entidade          VARCHAR(30)  NOT NULL,
    entidade_id       BIGINT,
    resumo            VARCHAR(300) NOT NULL,
    dados_anteriores  VARCHAR(2000),
    dados_posteriores VARCHAR(2000),
    criado_em         TIMESTAMP    NOT NULL,
    CONSTRAINT fk_atividades_projeto FOREIGN KEY (projeto_id) REFERENCES projetos (id) ON DELETE CASCADE,
    CONSTRAINT fk_atividades_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);
CREATE INDEX idx_atividades_projeto ON atividades (projeto_id, criado_em);

CREATE TABLE notificacoes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinatario_id BIGINT       NOT NULL,
    tipo            VARCHAR(60)  NOT NULL,
    mensagem        VARCHAR(600) NOT NULL,
    lida            BOOLEAN      NOT NULL DEFAULT FALSE,
    projeto_id      BIGINT,
    tarefa_id       BIGINT,
    criado_em       TIMESTAMP    NOT NULL,
    CONSTRAINT fk_notificacoes_destinatario FOREIGN KEY (destinatario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_notificacoes_projeto FOREIGN KEY (projeto_id) REFERENCES projetos (id),
    CONSTRAINT fk_notificacoes_tarefa FOREIGN KEY (tarefa_id) REFERENCES tarefas (id) ON DELETE SET NULL
);
CREATE INDEX idx_notificacoes_destinatario ON notificacoes (destinatario_id, lida, criado_em);
